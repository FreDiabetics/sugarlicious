    @Test fun upperRightGaugeFitsFullStepsWithoutEllipsis() {
        val caption = slot(7).need("Complication[@type='RANGED_VALUE']/PartText/TextCircular")
        assertEquals("FALSE", caption.attr("ellipsis"))
        val font =
            Files.newInputStream(root.resolve("watchfaces/sugarlicious-orbit/src/main/res/font/inter_tight.ttf")).use { Font.createFont(Font.TRUETYPE_FONT, it) }.deriveFont(
                caption
                    .need("Font")
                    .number("size")
                    .toInt()
                    .toFloat(),
            )
        val length = caption.number("width") / 2 * Math.toRadians((caption.number("endAngle") - caption.number("startAngle") + 360) % 360)
        assertTrue(font.getStringBounds("100.000", FontRenderContext(AffineTransform(), true, true)).width < length - 12)
    }

